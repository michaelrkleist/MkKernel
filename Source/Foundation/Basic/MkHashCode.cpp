#include "Foundation\MkFoundationPCH.h"
#include "Basic\MkHashCode.h"

// Static initializations.
namespace
{
mkuint64 sFNVOffset = 14695981039346656037ull; 
mkuint64 sFNVPrime = 1099511628211ull; 
}


////////////////////////////////////////////////////////////////////////////////////////////////////
// MkHashCode
////////////////////////////////////////////////////////////////////////////////////////////////////

MkHashCode& MkHashCode::Hash(mkbyte* pBytes, const mkuint64 byteCnt)
{
    mkbyte* pEndByte = pBytes + byteCnt;
    for (mkbyte* pByte = pBytes; pByte < pEndByte; ++pByte)
    {
        m_hashCode ^= *pByte;
        m_hashCode *= sFNVPrime;
    }

    return *this;
}
