MkUID::MkUID(const MkAString& uidStr)
{
    if (uidStr[0] == '{')
    {
        ::CLSIDFromString(uidStr.GetWString().get(), &m_uid);
    }
    else
    {
        MkAString wellFormedUIDStr("{%s}", uidStr.GetCString());
        ::CLSIDFromString(wellFormedUIDStr.GetWString().get(), &m_uid);
    }
}