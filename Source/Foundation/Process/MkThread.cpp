#include "Foundation\MkFoundationPCH.h"
#include "Process\MkThread.h"

// Mk includes.
#include "Process\MkOSEvent.h"

// Static initializations.
namespace
{
MkConstAString sExitStr = "Exit";
}


////////////////////////////////////////////////////////////////////////////////////////////////////
// MkThread
////////////////////////////////////////////////////////////////////////////////////////////////////

MkThread::MkThread(const MkAString& name) :
    m_name(name),
    m_rExitEvent(std::make_shared<MkOSEvent>(name + sExitStr, true))
{
}

////////////////////////////////////////////////////////////////////////////////////////////////////

MkThread::~MkThread()
{
    bool terminated = TerminateThread(m_threadHandle, 0);
    bool closed = CloseHandle(m_threadHandle);
}

////////////////////////////////////////////////////////////////////////////////////////////////////

void MkThread::StartThread()
{
    m_thread = std::thread(&MkThread::StartExecution, this);   
}

////////////////////////////////////////////////////////////////////////////////////////////////////

void MkThread::StartExecution()
{
    m_thread.detach();
    m_threadId = GetCurrentThreadId();
    m_threadHandle = OpenThread(THREAD_ALL_ACCESS, FALSE, m_threadId);

    Execute();
}