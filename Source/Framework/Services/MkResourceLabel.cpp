bool MkSimpleResourceLabel::Satisfies(const std::shared_ptr<MkResourceLabel>& rResourceLabel)
{
    auto rSimpleLabel = std::dynamic_pointer_cast<MkSimpleResourceLabel>(rResourceLabel);

    if (rSimpleLabel != nullptr) return Satisfies(rSimpleLabel);

    return false;
}